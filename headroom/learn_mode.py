"""Headroom learn mode for the bug bounty swarm.

Mines failed reconnaissance and exploitation sessions, extracts what went
wrong, and writes durable corrections into agent instruction files so the
next run starts smarter. Nothing is sent anywhere — all learning is local.

Usage:
    from headroom.learn_mode import SessionLearner

    learner = SessionLearner(instructions_dir="swarm/instructions")
    learner.ingest_session(session_log_path)
    learner.write_corrections()  # updates per-role instruction files
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# Patterns that indicate a dead end worth learning from
FAILURE_PATTERNS = [
    (r"403 forbidden", "Access denied — check scope and auth headers before brute-forcing"),
    (r"404 not found", "Endpoint missing — verify URL construction and trailing slashes"),
    (r"timeout|timed out", "Target slow or firewalled — increase timeout or switch to async"),
    (r"rate limit|429", "Rate limited — add jittered backoff, respect Retry-After"),
    (r"waf|blocked", "WAF triggered — rotate user agents and fragment payloads"),
    (r"cors.*misconfig", "CORS misconfiguration found — escalate to account takeover chain"),
    (r"open redirect", "Open redirect — chain with OAuth or password reset for impact"),
    (r"ssti", "SSTI detected — test sandbox escape for RCE"),
    (r"sqli|sql injection", "SQLi found — confirm with time-based payload, map to data exfil"),
    (r"idor", "IDOR candidate — test horizontal and vertical privilege boundaries"),
    (r"subdomain takeover", "Subdomain takeover — verify CNAME points to unclaimed service"),
    (r"exposed.*key|api_key|secret", "Secret exposure — check rotation status and blast radius"),
    (r"debug.*enabled|stack trace", "Debug surface — look for source disclosure or RCE gadgets"),
    (r"version.*outdated|eol", "Outdated component — cross-reference against known CVE databases"),
]


@dataclass
class LearnedCorrection:
    """One durable lesson extracted from a session."""
    pattern: str
    correction: str
    source_session: str
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    hit_count: int = 1


class SessionLearner:
    """Ingest session logs, extract corrections, write them to role instructions."""

    def __init__(self, instructions_dir: str | Path = "swarm/instructions"):
        self.instructions_dir = Path(instructions_dir)
        self.instructions_dir.mkdir(parents=True, exist_ok=True)
        self.corrections: dict[str, LearnedCorrection] = self._load_existing()

    def _load_existing(self) -> dict[str, LearnedCorrection]:
        store = self.instructions_dir / "learned_corrections.json"
        if store.exists():
            try:
                data = json.loads(store.read_text())
                return {
                    k: LearnedCorrection(**v) for k, v in data.items()
                }
            except (json.JSONDecodeError, TypeError) as exc:
                logger.warning("Could not load existing corrections: %s", exc)
        return {}

    def ingest_session(self, session_log: str | Path) -> list[LearnedCorrection]:
        """Parse a session log and extract new corrections."""
        path = Path(session_log)
        if not path.exists():
            logger.error("Session log not found: %s", path)
            return []

        text = path.read_text(errors="ignore")
        found: list[LearnedCorrection] = []
        for pattern, correction in FAILURE_PATTERNS:
            if re.search(pattern, text, re.IGNORECASE):
                key = pattern
                if key in self.corrections:
                    self.corrections[key].hit_count += 1
                else:
                    self.corrections[key] = LearnedCorrection(
                        pattern=pattern,
                        correction=correction,
                        source_session=str(path.name),
                    )
                found.append(self.corrections[key])
        return found

    def write_corrections(self) -> Path:
        """Persist corrections and append them to each role's instruction file."""
        store = self.instructions_dir / "learned_corrections.json"
        store.write_text(json.dumps(
            {k: vars(v) for k, v in self.corrections.items()},
            indent=2,
        ))

        # Append a learned-lessons block to every role instruction file
        block_lines = ["", "## Learned Lessons (auto-generated by learn mode)", ""]
        for corr in sorted(self.corrections.values(), key=lambda c: -c.hit_count):
            block_lines.append(
                f"- **{corr.pattern}** (seen {corr.hit_count}x): {corr.correction}"
            )
        block = "\n".join(block_lines) + "\n"

        for role_file in self.instructions_dir.glob("*.md"):
            if role_file.name == "learned_corrections.json":
                continue
            existing = role_file.read_text()
            # Replace any previous learned block rather than duplicating
            cleaned = re.sub(
                r"\n## Learned Lessons \(auto-generated by learn mode\)[\s\S]*?\Z",
                "",
                existing,
            )
            role_file.write_text(cleaned.rstrip() + "\n" + block)

        return store

    def summary(self) -> str:
        """Human-readable summary of what the swarm has learned."""
        if not self.corrections:
            return "No corrections learned yet."
        lines = [f"{len(self.corrections)} lessons across sessions:"]
        for corr in sorted(self.corrections.values(), key=lambda c: -c.hit_count):
            lines.append(f"  [{corr.hit_count}x] {corr.correction}")
        return "\n".join(lines)
